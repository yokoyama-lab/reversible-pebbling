#!/usr/bin/env python3
"""Generate the Zone I ledger cover: LedgerCoverP*.v and LedgerCover.v.

    python3 gencover.py QLO QHI MARGIN OUTDIR [PER_PART] [MAXWINDOWS]

The grid is adaptive.  At each node the largest window width whose ledger
enclosure still clears MARGIN is found by bisection and then shrunk by
10%; widths run over two orders of magnitude across [1.45, 3.25] because
the ledger's own margin does (it is tightest at q1 ~ 2.4 and very slack
near 3.25).

Every constant is computed in ledger.py with mpmath at mp.dps = 40 and
rounded OUTWARD.  Nothing is guessed.  A constant that came out too tight
makes `rocq c` fail on the corresponding `interval` call, so the prover,
not this script, is the arbiter of correctness.

The cover is split into parts because a single file costs about 11 MB of
prover memory per window; the parts are mutually independent (consecutive
parts repeat the shared boundary node), so `make -jN` builds them in
parallel.
"""

import sys, os
from mpmath import mp, mpf
import ledger as L
import emit as E

HERE = os.path.dirname(os.path.abspath(__file__))
H = mpf('1e-5')          # difference-quotient step at a node
BISECT = 12


def grid_point(q):
    return mp.nint(q * mpf(10) ** E.DQ) / mpf(10) ** E.DQ


_ncache = {}


def node(q):
    k = str(q)
    if k not in _ncache:
        _ncache[k] = E.node_data(q, H)
    return _ncache[k]


def build(qlo, qhi, margin, maxwin=None):
    """returns (nodes, windows); windows[i] spans nodes[i]..nodes[i+1]"""
    nodes, wins = [], []
    qa = grid_point(qlo)
    ndA = node(qa)
    nodes.append(ndA)
    top = grid_point(qhi)
    while qa < top:
        lo, hi = mpf('2e-5'), min(mpf('8e-2'), (top - qa) * 2)
        best = None
        for _ in range(BISECT):
            mid = grid_point((lo + hi) / 2)
            if mid <= 0:
                break
            qb = min(mid + qa, top)
            w = L.window(qa, qb, node(qb)['blo'], ndA['bhi'])
            if w['led'].lo > margin:
                best = qb
                lo = qb - qa
            else:
                hi = qb - qa
        if best is None:
            raise SystemExit("no window closes at q1 = %s" % mp.nstr(qa, 10))
        qb = min(grid_point(qa + (best - qa) * mpf('0.9')), top)
        if qb <= qa:
            raise SystemExit("degenerate window at %s" % mp.nstr(qa, 10))
        nd = node(qb)
        w = L.window(qa, qb, nd['blo'], ndA['bhi'])
        if w['led'].lo <= 0:
            raise SystemExit("shrunk window failed at %s" % mp.nstr(qa, 10))
        nodes.append(nd)
        wins.append(w)
        if len(wins) % 25 == 0:
            sys.stderr.write("  %4d windows, at q1 = %s (W = %s)\n"
                             % (len(wins), mp.nstr(qb, 8), mp.nstr(qb - qa, 4)))
            sys.stderr.flush()
        qa, ndA = qb, nd
        if maxwin and len(wins) >= maxwin:
            break
    return nodes, wins


PART_HDR = '''(** * Zone I ledger cover, part %(k)d: q1 in [%(qa)s, %(qb)s]
    -- MACHINE-GENERATED by gen/gencover.py; do not edit by hand.
    Windows %(w0)d..%(w1)d of %(ntot)d.  See LedgerCover.v. *)

From Stdlib Require Import Reals Lra.
From Interval Require Import Tactic.
From RevPebblingRocq Require Import KappaStar RhoEnclose LedgerParam EnvelopeE
  SlopeWindow LedgerA CoverGlue.
Local Open Scope R_scope.

'''


def main():
    qlo, qhi, margin = mpf(sys.argv[1]), mpf(sys.argv[2]), mpf(sys.argv[3])
    outdir = sys.argv[4]
    per = int(sys.argv[5]) if len(sys.argv) > 5 else 40
    maxwin = int(sys.argv[6]) if len(sys.argv) > 6 else None

    nodes, wins = build(qlo, qhi, margin, maxwin)
    n = len(wins)
    covered_hi = nodes[n]['q']
    parts = []

    for k, w0 in enumerate(range(0, n, per)):
        w1 = min(w0 + per, n) - 1
        name = "LedgerCoverP%02d" % k
        parts.append((name, w0, w1))
        with open(os.path.join(outdir, name + '.v'), 'w') as f:
            f.write(PART_HDR % dict(k=k, w0=w0, w1=w1, ntot=n,
                                    qa=mp.nstr(nodes[w0]['q'], 10),
                                    qb=mp.nstr(nodes[w1 + 1]['q'], 10)))
            pfx = "p%d_" % k
            for i in range(w0, w1 + 2):          # nodes, boundary repeated
                f.write(E.emit_node(i, nodes[i], pfx=pfx))
            for i in range(w0, w1 + 1):
                f.write(E.emit_window(i, wins[i], nodes[i], nodes[i + 1],
                                      pfx=pfx))

    with open(os.path.join(outdir, 'LedgerCover.v'), 'w') as f:
        f.write(TOP % dict(
            qlo=mp.nstr(nodes[0]['q'], 10), qhi=mp.nstr(covered_hi, 10),
            n=n, np=len(parts),
            wmin=mp.nstr(min(w['qb'] - w['qa'] for w in wins), 4),
            wmax=mp.nstr(max(w['qb'] - w['qa'] for w in wins), 4),
            vmin=mp.nstr(min(w['val'] for w in wins), 6),
            gap=("The cover reaches the top of the Zone I range."
                 if covered_hi >= mpf('3.25') else
                 "NOT COVERED: q1 in (%s, 3.25].  Nothing below claims\n"
                 "    anything about that sub-range." % mp.nstr(covered_hi, 10)),
            req="\n  ".join(p[0] for p in parts),
            tbl="\n".join("    %-18s windows %4d..%-4d   q1 in [%s, %s]"
                          % (nm, a, b, mp.nstr(nodes[a]['q'], 9),
                             mp.nstr(nodes[b + 1]['q'], 9))
                          for nm, a, b in parts),
            first=mp.nstr(nodes[0]['q'], 10),
            firstend=mp.nstr(nodes[1]['q'], 10)))

    sys.stderr.write("%d windows, %d nodes, %d parts; covered [%s, %s]\n"
                     % (n, n + 1, len(parts), mp.nstr(nodes[0]['q'], 10),
                        mp.nstr(covered_hi, 10)))


TOP = '''(** * The Zone I ledger cover  (Rocq + CoqInterval)  -- GENERATED INDEX

    MACHINE-GENERATED by gen/gencover.py; do not edit by hand.

    [LedgerA.window_24] closes Lemma A's ledger on the single window
    q1 in (2.4, 2.4005), with the slope bracket [BLO,BHI] ASSUMED.  This
    cover replicates that across a grid and strengthens it: the slope
    bracket is DERIVED at every node from three point enclosures of f
    ([CoverGlue.slope_upper_eps] / [slope_lower_eps], on top of
    [LedgerParam.beta_bracket_eps]) and transported to the CLOSED window
    by [CoverGlue.slope_hi_eps] / [slope_lo_eps].  Consecutive windows
    share a node, so the union is a closed interval with no gaps -- not a
    union of open windows that misses its own grid points.

    NOTE ON THE TWO eps.  [LedgerA.EPS = 1/100] is the trial profile's
    design constant, unchanged.  The [eps] quantified in each window
    below is the MINIMALITY SLACK, bounded by [CoverGlue.EPSB = 1e-11].
    They are unrelated.

    ** WHAT IS COVERED

    q1 in [%(qlo)s, %(qhi)s], by %(n)d closed windows in %(np)d parts.
    Window widths run from %(wmin)s to %(wmax)s: they are chosen
    adaptively, because the ledger's true margin varies by an order of
    magnitude over the range (it is tightest at q1 ~ 2.4).  The smallest
    certified lower bound on the ledger, over all %(n)d windows, is
    %(vmin)s > 0.

    %(gap)s

    ** WHAT EACH WINDOW SAYS

    [window_i eps q1 b1 ... : 0 < eps -> eps <= EPSB ->
                              qa <= q1 <= qb -> ... -> val <= ledger ...]
    for every q1 in the window, every eps-minimiser slope b1 there, and
    every root of g at the three slopes involved.  The hypotheses are
    those of [window_24] MINUS the assumed slope bracket, PLUS the
    existence of eps-minimiser slopes at the window's two nodes.

    ** eps-MINIMALITY, NOT EXACT MINIMALITY

    [EminEps eps b q1 f1] asks only that the q1-line be lowest to within
    eps.  That is the version [EminExists.emin_eps_exists] PRODUCES: for
    every slope b > 0 and every eps > 0 an eps-minimiser exists, straight
    from the completeness of R -- no compactness, no continuity of rho_c.
    Exact minimality (the old [EminRel]) was never shown satisfiable at
    all.

    The price is that each node's slope bracket widens by C = 2 eps / h
    on each side, and [CoverGlue.slope_hi_eps]/[slope_lo_eps] carry that
    same C uniformly across the closed window -- no division by the
    window width, so the narrowest windows pay no more than the widest.
    MEASURED (on the previous, 925-window grid): every window still
    closes up to C = 3.987e-5, i.e. eps = 1.99e-10, the binding window
    being the one at q1 ~ 2.1179.  EPSB is a factor 20 inside that.

    ** WHAT IS NOT PROVED HERE

    That the ledger being positive implies Zone I's one-step inequality:
    that reduction is the appendix's, and is not formalised.  Zone 0
    (beta <= 0.12), Zone II (qtilde < 0.3) and the transfer principle are
    elsewhere.  And the design constants EPS, LAM, MU and QS of the
    trial profile are constants of the ansatz, not objects that this
    development characterises.

    Nor is the node hypothesis discharged.  [EminExists] produces, for a
    GIVEN SLOPE, a q that eps-minimises there; a node needs the converse
    -- for a GIVEN q, a slope that q eps-minimises at -- which says f is
    on its own lower convex envelope at that q.  That is false below
    q ~ 0.5 and is not proved here for [1.45, 3.25].

    ** THE PARTS

%(tbl)s
*)

From RevPebblingRocq Require Export
  %(req)s.
'''

if __name__ == '__main__':
    main()
